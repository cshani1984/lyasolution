/**
 * Writes src/environments/environment.prod.ts before production builds.
 * Vercel: set SUPABASE_ANON_KEY (required). Optionally override SUPABASE_URL.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Default REST URL for this Supabase project when SUPABASE_URL is unset. */
const DEFAULT_SUPABASE_URL = 'https://pntibywmzseguynujsle.supabase.co';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dest = join(root, 'src', 'environments', 'environment.prod.ts');

const url = process.env.SUPABASE_URL ?? DEFAULT_SUPABASE_URL;
const key = process.env.SUPABASE_ANON_KEY ?? '';

const content = `/* Generated by scripts/write-env.mjs — do not edit manually */
export const environment = {
  production: true,
  supabaseUrl: ${JSON.stringify(url)},
  supabaseAnonKey: ${JSON.stringify(key)},
};
`;

writeFileSync(dest, content, 'utf8');
